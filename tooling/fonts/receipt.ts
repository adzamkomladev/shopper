import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

// Satori reads ttf/otf/woff, not woff2. Run `vp run fonts:receipt` after bumping @fontsource/geist.
const weights = [400, 700]; // the only weights ReceiptView uses
const require = createRequire(import.meta.url);
const out = new URL("../../packages/hardware/src/render/fonts.gen.ts", import.meta.url);

const lines = await Promise.all(
  weights.map(async (weight) => {
    const file = require.resolve(`@fontsource/geist/files/geist-latin-${weight}-normal.woff`);
    return `  ${weight}: "${(await readFile(file)).toString("base64")}",`;
  }),
);
await writeFile(
  out,
  `// Generated by tooling/fonts/receipt.ts. Do not edit.\nexport const geistWoff: Record<number, string> = {\n${lines.join("\n")}\n};\n`,
);
